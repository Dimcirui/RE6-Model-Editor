"""Name hashes of the MT Framework resources, identical to the MHW Model Editor's.

* material name hash (the u32 in the .mod material table and in the .mrl material entry) = jamcrc32(name), i.e.
  ~crc32(name); verified on RE6 materials: 'pl_skin' = 0x68b3d093, 'pl_snow' = 0x5c491d3e, 'Null' = 0x7a06ac8e ...
* shader parameter hashes (texture slots, sampler states, constant buffers ...): the upper 20 bits are
  jamcrc32(name) & 0xFFFFF, the lower 12 bits are a code (the command header repeats them). The names come from
  shader_names.py (albam's table, generated by tools/make_shader_names.py).
"""
from __future__ import annotations

import zlib


def jamcrc32(name: str) -> int:
    # game names are ASCII (same bytes in utf-8); utf-8 also hashes Blender names with other characters (e.g. Chinese)
    return (zlib.crc32(name.encode('utf-8')) & 0xFFFFFFFF) ^ 0xFFFFFFFF


def name20(name: str) -> int:
    return jamcrc32(name) & 0xFFFFF


# material names that resolve: from the MHW dictionary (Null, Shadow, Material, pl_skin, pl_snow) and from guessing names
# out of the game's texture names (tools/hash_guess.py). The guess tried ~13 million names against 8331 hashes, so about
# 25 hits are expected by chance; only names with many uses (the player family pl_skin / pl_base / pl_cloth / pl_hair /
# pl_nuki / pl_eyeshadow with their numbered variants, the wp_Totan weapons) are kept, singletons were dropped
