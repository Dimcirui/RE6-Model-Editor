MATERIAL_NAMES = {jamcrc32(n): n for n in KNOWN_MATERIALS}


def slot_name(h: int) -> str:
    """name of a sampler / texture slot or of any other shader parameter hash (tAlbedoMap, SSAlbedoMap, CBMaterial ...)"""
    from .shader_names import name_of
    return name_of(h)


# names learned while the editor runs (the Blender layer fills it from the scene and from the user's dictionary file,
# blender/material_names.py); the .mod has no name table, so this is where names of new materials come from
LEARNED = {}


def learn(name: str):
    """remember a material name; returns its hash (None for an empty name or MAT_<hash>)"""
    name = (name or '').strip()
    if not name or (name.startswith('MAT_') and len(name) == 12):
        return None
    h = jamcrc32(name)
    if h not in MATERIAL_NAMES:
        LEARNED[h] = name
    return h


def material_name(h: int) -> str:
    return MATERIAL_NAMES.get(h) or LEARNED.get(h, '')
