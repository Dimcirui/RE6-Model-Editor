def _table():
    d = {}
    for k, v in ZH.items():
        d[('*', k)] = v
        d[('Operator', k)] = v
    return d


def register():
    t = {'zh_HANS': _table(), 'zh_CN': _table(), 'zh_HANT': _table(), 'zh_TW': _table()}
    try:
        bpy.app.translations.register(ROOT, t)
    except ValueError:          # already registered (reload)
        bpy.app.translations.unregister(ROOT)
        bpy.app.translations.register(ROOT, t)


def unregister():
    try:
        bpy.app.translations.unregister(ROOT)
    except (ValueError, KeyError):
        pass


